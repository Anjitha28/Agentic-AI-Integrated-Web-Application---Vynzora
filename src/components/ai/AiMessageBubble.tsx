'use client';

import React, { useState } from 'react';
import {
  Sparkles,
  User,
  Volume2,
  VolumeX,
  Copy,
  Check,
  FileText,
  FileSpreadsheet,
  Download,
  BarChart3,
  PieChart as PieIcon,
  TrendingUp,
  Table as TableIcon,
  ArrowUpRight,
  Info,
} from 'lucide-react';
import {
  ResponsiveContainer,
  BarChart,
  Bar,
  XAxis,
  YAxis,
  Tooltip,
  PieChart,
  Pie,
  Cell,
  AreaChart,
  Area,
} from 'recharts';
import jsPDF from 'jspdf';
import * as XLSX from 'xlsx';
import { AiChatResponse } from '@/lib/ai/gemini';
import { SupportedLanguage } from '@/lib/ai/languageUtils';

const CHART_COLORS = ['#3b82f6', '#10b981', '#f59e0b', '#8b5cf6', '#ec4899', '#06b6d4'];

export interface ChatMessage {
  id: string;
  role: 'user' | 'assistant';
  content: string;
  timestamp: string;
  language?: SupportedLanguage;
  toolsUsed?: string[];
  chartData?: AiChatResponse['chartData'];
  tableData?: AiChatResponse['tableData'];
  reportData?: AiChatResponse['reportData'];
}

interface AiMessageBubbleProps {
  message: ChatMessage;
  onSpeak?: (text: string, lang?: SupportedLanguage) => void;
  isSpeaking?: boolean;
  onStopSpeak?: () => void;
}

export default function AiMessageBubble({
  message,
  onSpeak,
  isSpeaking,
  onStopSpeak,
}: AiMessageBubbleProps) {
  const [copied, setCopied] = useState(false);
  const isAssistant = message.role === 'assistant';

  const handleCopy = (text: string) => {
    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownloadPdf = () => {
    if (!message.reportData) return;
    const doc = new jsPDF();
    const r = message.reportData;

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(18);
    doc.setTextColor(24, 30, 48);
    doc.text(r.title, 14, 20);

    doc.setFontSize(10);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(100, 110, 130);
    doc.text(`Report Period: ${r.period} | Generated by Vynzora AI`, 14, 27);

    // Divider
    doc.setDrawColor(220, 225, 235);
    doc.line(14, 31, 196, 31);

    // Executive Summary
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(12);
    doc.setTextColor(30, 41, 59);
    doc.text('1. Executive Summary', 14, 39);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9.5);
    doc.setTextColor(71, 85, 105);
    const splitSummary = doc.splitTextToSize(r.executiveSummary, 180);
    doc.text(splitSummary, 14, 46);

    // Key Metrics
    let currentY = 46 + splitSummary.length * 5 + 6;
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(12);
    doc.setTextColor(30, 41, 59);
    doc.text('2. Key Business Metrics', 14, currentY);

    currentY += 7;
    doc.setFontSize(9);
    doc.setFont('helvetica', 'normal');
    r.metrics.forEach((m, idx) => {
      const col = idx % 2 === 0 ? 14 : 105;
      const rowY = currentY + Math.floor(idx / 2) * 8;
      doc.text(`• ${m.label}: ${m.value}`, col, rowY);
    });

    currentY += Math.ceil(r.metrics.length / 2) * 8 + 8;

    // Insights & Takeaways
    if (r.insights && r.insights.length > 0) {
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(12);
      doc.setTextColor(30, 41, 59);
      doc.text('3. Key Business Findings', 14, currentY);

      currentY += 7;
      doc.setFontSize(9);
      doc.setFont('helvetica', 'normal');
      r.insights.forEach((insight) => {
        const splitInsight = doc.splitTextToSize(`• ${insight}`, 180);
        doc.text(splitInsight, 14, currentY);
        currentY += splitInsight.length * 5;
      });
      currentY += 5;
    }

    // Recommendations
    if (r.recommendations && r.recommendations.length > 0) {
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(12);
      doc.setTextColor(30, 41, 59);
      doc.text('4. Strategic Action Items', 14, currentY);

      currentY += 7;
      doc.setFontSize(9);
      doc.setFont('helvetica', 'normal');
      r.recommendations.forEach((rec) => {
        const splitRec = doc.splitTextToSize(`→ ${rec}`, 180);
        doc.text(splitRec, 14, currentY);
        currentY += splitRec.length * 5;
      });
    }

    doc.save(`Vynzora_Business_Report_${Date.now()}.pdf`);
  };

  const handleDownloadExcel = () => {
    if (!message.reportData && !message.tableData) return;
    const wb = XLSX.utils.book_new();

    if (message.reportData) {
      const metricsData = message.reportData.metrics.map((m) => ({
        Metric: m.label,
        Value: m.value,
      }));
      const wsMetrics = XLSX.utils.json_to_sheet(metricsData);
      XLSX.utils.book_append_sheet(wb, wsMetrics, 'Key Metrics');

      if (message.reportData.tables?.[0]) {
        const t = message.reportData.tables[0];
        const tableRows = t.rows.map((r) => {
          const rowObj: Record<string, any> = {};
          t.columns.forEach((col, idx) => {
            rowObj[col] = r[idx];
          });
          return rowObj;
        });
        const wsTable = XLSX.utils.json_to_sheet(tableRows);
        XLSX.utils.book_append_sheet(wb, wsTable, t.title.slice(0, 30));
      }
    } else if (message.tableData) {
      const ws = XLSX.utils.json_to_sheet(message.tableData.rows);
      XLSX.utils.book_append_sheet(wb, ws, 'Data');
    }

    XLSX.writeFile(wb, `Vynzora_Data_Export_${Date.now()}.xlsx`);
  };

  return (
    <div
      className={`flex gap-3 text-xs sm:text-sm animate-in fade-in-50 duration-200 ${
        isAssistant ? 'justify-start' : 'justify-end'
      }`}
    >
      {/* Assistant Avatar */}
      {isAssistant && (
        <div className="w-8 h-8 rounded-xl bg-gradient-to-tr from-brand-600 via-indigo-600 to-accent-500 flex items-center justify-center text-white shrink-0 shadow-md shadow-brand-500/20">
          <Sparkles className="w-4 h-4" />
        </div>
      )}

      {/* Message Bubble Container */}
      <div
        className={`max-w-[88%] sm:max-w-[85%] rounded-2xl p-4 space-y-3 ${
          isAssistant
            ? 'bg-slate-900/90 border border-slate-800 text-slate-100 shadow-xl'
            : 'bg-brand-600 text-white shadow-lg shadow-brand-600/20'
        }`}
      >
        {/* Header bar for assistant response */}
        {isAssistant && (
          <div className="flex items-center justify-between pb-2 border-b border-slate-800/80 text-[11px] text-slate-400">
            <div className="flex items-center gap-1.5 font-semibold text-brand-300">
              <span>Vynzora AI</span>
              {message.language && (
                <span className="px-1.5 py-0.2 rounded bg-slate-800 text-[10px] uppercase font-mono text-slate-300 border border-slate-700">
                  {message.language}
                </span>
              )}
            </div>

            <div className="flex items-center gap-2">
              {onSpeak && (
                <button
                  onClick={() => {
                    if (isSpeaking) {
                      onStopSpeak?.();
                    } else {
                      onSpeak(message.content, message.language);
                    }
                  }}
                  className="hover:text-white transition-colors p-1 rounded hover:bg-slate-800"
                  title={isSpeaking ? 'Stop voice' : 'Play response voice'}
                >
                  {isSpeaking ? (
                    <VolumeX className="w-3.5 h-3.5 text-rose-400 animate-pulse" />
                  ) : (
                    <Volume2 className="w-3.5 h-3.5" />
                  )}
                </button>
              )}

              <button
                onClick={() => handleCopy(message.content)}
                className="hover:text-white transition-colors p-1 rounded hover:bg-slate-800"
                title="Copy text"
              >
                {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              </button>
            </div>
          </div>
        )}

        {/* Text Content */}
        <div className="whitespace-pre-line leading-relaxed text-slate-200 font-normal">
          {message.content}
        </div>

        {/* Dynamic Chart Visualization */}
        {message.chartData && (
          <div className="p-3.5 rounded-xl bg-slate-950/80 border border-slate-800/90 space-y-2 mt-2">
            <div className="flex items-center gap-1.5 text-xs font-semibold text-white">
              <BarChart3 className="w-3.5 h-3.5 text-brand-400" />
              <span>{message.chartData.title}</span>
            </div>

            <div className="w-full h-48 sm:h-56 pt-2">
              <ResponsiveContainer width="100%" height="100%">
                {message.chartData.type === 'pie' ? (
                  <PieChart>
                    <Tooltip
                      contentStyle={{
                        backgroundColor: '#0f172a',
                        border: '1px solid #334155',
                        borderRadius: '8px',
                        fontSize: '11px',
                      }}
                    />
                    <Pie
                      data={message.chartData.data}
                      dataKey={message.chartData.dataKey}
                      nameKey={message.chartData.nameKey || 'name'}
                      cx="50%"
                      cy="50%"
                      outerRadius={75}
                      innerRadius={38}
                      paddingAngle={3}
                    >
                      {message.chartData.data.map((_, idx) => (
                        <Cell key={`cell-${idx}`} fill={CHART_COLORS[idx % CHART_COLORS.length]} />
                      ))}
                    </Pie>
                  </PieChart>
                ) : message.chartData.type === 'area' ? (
                  <AreaChart data={message.chartData.data}>
                    <XAxis
                      dataKey={message.chartData.nameKey || 'name'}
                      stroke="#64748b"
                      fontSize={10}
                    />
                    <YAxis stroke="#64748b" fontSize={10} />
                    <Tooltip
                      contentStyle={{
                        backgroundColor: '#0f172a',
                        border: '1px solid #334155',
                        borderRadius: '8px',
                        fontSize: '11px',
                      }}
                    />
                    <Area
                      type="monotone"
                      dataKey={message.chartData.dataKey}
                      stroke="#3b82f6"
                      fill="#3b82f6"
                      fillOpacity={0.25}
                    />
                  </AreaChart>
                ) : (
                  <BarChart data={message.chartData.data}>
                    <XAxis
                      dataKey={message.chartData.nameKey || 'name'}
                      stroke="#64748b"
                      fontSize={10}
                      tickFormatter={(val) => (typeof val === 'string' && val.length > 12 ? `${val.slice(0, 10)}...` : val)}
                    />
                    <YAxis stroke="#64748b" fontSize={10} />
                    <Tooltip
                      contentStyle={{
                        backgroundColor: '#0f172a',
                        border: '1px solid #334155',
                        borderRadius: '8px',
                        fontSize: '11px',
                      }}
                    />
                    <Bar dataKey={message.chartData.dataKey} fill="#3b82f6" radius={[4, 4, 0, 0]} />
                  </BarChart>
                )}
              </ResponsiveContainer>
            </div>
          </div>
        )}

        {/* Dynamic Data Table */}
        {message.tableData && (
          <div className="rounded-xl border border-slate-800 bg-slate-950/70 overflow-hidden mt-2">
            <div className="p-2.5 bg-slate-900/80 border-b border-slate-800 flex items-center justify-between text-xs font-semibold text-white">
              <span className="flex items-center gap-1.5">
                <TableIcon className="w-3.5 h-3.5 text-brand-400" />
                {message.tableData.title}
              </span>

              <button
                onClick={handleDownloadExcel}
                className="text-[11px] font-medium text-brand-300 hover:text-white flex items-center gap-1"
                title="Export this table to Excel"
              >
                <Download className="w-3 h-3" />
                <span>Export Excel</span>
              </button>
            </div>

            <div className="overflow-x-auto max-h-56 overflow-y-auto">
              <table className="w-full text-left text-[11px]">
                <thead className="bg-slate-900/90 text-slate-400 border-b border-slate-800 sticky top-0">
                  <tr>
                    {message.tableData.columns.map((c) => (
                      <th key={c} className="p-2 font-semibold whitespace-nowrap">
                        {c}
                      </th>
                    ))}
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-800/60 text-slate-300">
                  {message.tableData.rows.map((row, idx) => (
                    <tr key={idx} className="hover:bg-slate-800/40 transition-colors">
                      {message.tableData!.columns.map((c) => (
                        <td key={c} className="p-2 whitespace-nowrap">
                          {String(row[c] ?? '')}
                        </td>
                      ))}
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>
        )}

        {/* Full Executive Business Report Card */}
        {message.reportData && (
          <div className="p-4 rounded-2xl bg-gradient-to-b from-slate-900 to-slate-950 border border-brand-500/30 shadow-xl space-y-4 mt-3">
            <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 border-b border-slate-800 pb-3">
              <div>
                <span className="px-2 py-0.5 rounded text-[10px] font-bold bg-brand-500/20 text-brand-300 uppercase">
                  Executive Intelligence Report
                </span>
                <h4 className="text-sm font-bold text-white mt-1">{message.reportData.title}</h4>
                <span className="text-[10px] text-slate-400">Period: {message.reportData.period}</span>
              </div>

              {/* PDF & Excel Download Buttons */}
              <div className="flex items-center gap-2">
                <button
                  onClick={handleDownloadPdf}
                  className="px-2.5 py-1.5 rounded-lg bg-rose-600/20 hover:bg-rose-600/30 border border-rose-500/40 text-rose-300 text-xs font-semibold flex items-center gap-1.5 transition-colors"
                >
                  <FileText className="w-3.5 h-3.5" />
                  <span>Download PDF</span>
                </button>
                <button
                  onClick={handleDownloadExcel}
                  className="px-2.5 py-1.5 rounded-lg bg-emerald-600/20 hover:bg-emerald-600/30 border border-emerald-500/40 text-emerald-300 text-xs font-semibold flex items-center gap-1.5 transition-colors"
                >
                  <FileSpreadsheet className="w-3.5 h-3.5" />
                  <span>Export Excel</span>
                </button>
              </div>
            </div>

            {/* Metrics Grid */}
            <div className="grid grid-cols-2 sm:grid-cols-3 gap-2">
              {message.reportData.metrics.map((m) => (
                <div key={m.label} className="p-2.5 rounded-xl bg-slate-900 border border-slate-800">
                  <span className="text-[10px] text-slate-400 block">{m.label}</span>
                  <span className="text-sm font-bold text-white font-mono">{m.value}</span>
                </div>
              ))}
            </div>

            {/* Strategic Insights */}
            {message.reportData.insights && message.reportData.insights.length > 0 && (
              <div className="space-y-1.5 text-[11px] text-slate-300">
                <span className="font-semibold text-white block">Key Business Insights:</span>
                {message.reportData.insights.map((ins, idx) => (
                  <div key={idx} className="flex items-start gap-1.5">
                    <TrendingUp className="w-3 h-3 text-brand-400 mt-0.5 shrink-0" />
                    <span>{ins}</span>
                  </div>
                ))}
              </div>
            )}
          </div>
        )}
      </div>

      {/* User Avatar */}
      {!isAssistant && (
        <div className="w-8 h-8 rounded-xl bg-slate-800 border border-slate-700 flex items-center justify-center text-slate-300 shrink-0">
          <User className="w-4 h-4" />
        </div>
      )}
    </div>
  );
}

